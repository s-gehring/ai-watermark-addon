import type { Platform } from './messages';

export type LookupPlatform = 'pixiv' | 'commons';

export interface LookupResult {
  labels: Map<string, boolean>;
  truncated: boolean;
}

export const LOOKUP_BATCH: Readonly<Record<LookupPlatform, number>> = { pixiv: 50, commons: 20 };
const MAX_ENCODED_TITLES = 4000;

const WIKIMEDIA_HOST =
  /(?:^|\.)(?:wikipedia|wikimedia|wiktionary|wikibooks|wikinews|wikiquote|wikisource|wikiversity|wikivoyage|wikidata|mediawiki)\.org$/;
const PIXIV_WORK =
  /^https:\/\/i\.pximg\.net\/(?:c\/[^/]+\/)?(?:img-master|img-original|custom-thumb)\/img\/(?:\d+\/){6}(\d+)(?:-[0-9a-f]+)?_/;
const WIXMP_FILE = /^(https:\/\/[\w-]+\.wixmp\.com)\/(?:intermediary\/)?(f\/[^?#]+?)(?:\/v1\/[^?#]*)?(?:[?#].*)?$/;
const COMMONS_FILE = /^https:\/\/(?:upload|thumb)\.wikimedia\.org\/wikipedia\/commons\/(?:thumb\/)?[0-9a-f]\/[0-9a-f]{2}\/([^/?#]+)/;
const COMMONS_FILE_PAGE = /^\/wiki\/(File:[^?#]+)$/;
const DEVIANTART_STATE = 'window.__INITIAL_STATE__ = JSON.parse("';

const AI_CATEGORY = /\bAI[- ]generated\b|^Images generated by /i;
const ABOUT_AI_CATEGORY = /^(?:Photographs of|Videos about|Criticism of|Unconfirmed|EU Icons for) /i;
const PHOTOGRAPH_OF_AI = /^Photographs of AI[- ]generated\b/i;

export function platformOf(hostname: string): Platform | null {
  const host = hostname.toLowerCase();
  if (host === 'pixiv.net' || host === 'www.pixiv.net') return 'pixiv';
  if (host === 'deviantart.com' || host.endsWith('.deviantart.com')) return 'deviantart';
  if (WIKIMEDIA_HOST.test(host)) return 'commons';
  return null;
}

function decoded(part: string): string | null {
  try {
    return decodeURIComponent(part);
  } catch {
    return null;
  }
}

function commonsTitle(encoded: string): string | null {
  const name = decoded(encoded)?.replaceAll('_', ' ').trim();
  return name ? name : null;
}

export function labelKeyOf(platform: Platform, imageUrl: string): string | null {
  if (platform === 'pixiv') return PIXIV_WORK.exec(imageUrl)?.[1] ?? null;
  if (platform === 'deviantart') {
    const file = WIXMP_FILE.exec(imageUrl);
    return file ? `${file[1]}/${file[2]}` : null;
  }
  const file = COMMONS_FILE.exec(imageUrl);
  const title = file && commonsTitle(file[1]);
  return title ? `File:${title}` : null;
}

export function isLookupKey(platform: LookupPlatform, key: string): boolean {
  if (platform === 'pixiv') return /^\d{1,12}$/.test(key);
  return /^File:[^|#<>[\]{}\x00-\x1f]{1,240}$/.test(key);
}

export function lookupBatches(platform: LookupPlatform, keys: string[]): string[][] {
  const batches: string[][] = [];
  let length = 0;
  for (const key of keys) {
    const cost = platform === 'commons' ? encodeURIComponent(key).length + 3 : 0;
    const batch = batches.at(-1);
    if (batch && batch.length < LOOKUP_BATCH[platform] && length + cost <= MAX_ENCODED_TITLES) {
      batch.push(key);
      length += cost;
    } else {
      batches.push([key]);
      length = cost;
    }
  }
  return batches;
}

export function lookupUrl(platform: LookupPlatform, keys: string[]): string {
  if (platform === 'pixiv') {
    const query = keys.map((id) => `illust_ids%5B%5D=${id}`).join('&');
    return `https://www.pixiv.net/ajax/illust/recommend/illusts?${query}`;
  }
  const params = new URLSearchParams({
    action: 'query',
    format: 'json',
    formatversion: '2',
    origin: '*',
    prop: 'categories',
    cllimit: 'max',
    titles: keys.join('|'),
  });
  return `https://commons.wikimedia.org/w/api.php?${params}`;
}

function recordOf(value: unknown): Record<string, unknown> {
  return value && typeof value === 'object' ? (value as Record<string, unknown>) : {};
}

function listOf(value: unknown): Record<string, unknown>[] {
  return Array.isArray(value) ? value.map(recordOf) : [];
}

function pixivLabels(response: unknown): LookupResult {
  const labels = new Map<string, boolean>();
  for (const work of listOf(recordOf(recordOf(response).body).illusts)) {
    if (typeof work.id === 'string' || typeof work.id === 'number') labels.set(String(work.id), work.aiType === 2);
  }
  return { labels, truncated: false };
}

export function isAiCategory(name: string): boolean {
  return AI_CATEGORY.test(name) && !ABOUT_AI_CATEGORY.test(name);
}

export function hasAiCategory(names: string[]): boolean {
  return names.some(isAiCategory) && !names.some((name) => PHOTOGRAPH_OF_AI.test(name));
}

const withoutNamespace = (title: unknown) => String(title ?? '').replace(/^Category:/, '');

function commonsLabels(response: unknown): LookupResult {
  const { query, continue: more } = recordOf(response);
  const { pages, normalized } = recordOf(query);
  const resumesAt = more === undefined ? Infinity : parseInt(String(recordOf(more).clcontinue), 10);
  const labels = new Map<string, boolean>();
  for (const page of listOf(pages)) {
    const listed = page.missing === true || (typeof page.pageid === 'number' && page.pageid < resumesAt);
    if (typeof page.title !== 'string' || !listed) continue;
    labels.set(page.title, hasAiCategory(listOf(page.categories).map((category) => withoutNamespace(category.title))));
  }
  for (const { from, to } of listOf(normalized)) {
    const label = typeof to === 'string' ? labels.get(to) : undefined;
    if (typeof from === 'string' && label !== undefined) labels.set(from, label);
  }
  return { labels, truncated: more !== undefined };
}

export function parseLookup(platform: LookupPlatform, response: unknown): LookupResult {
  return platform === 'pixiv' ? pixivLabels(response) : commonsLabels(response);
}

export function commonsFilePage(hostname: string, pathname: string): string | null {
  if (hostname !== 'commons.wikimedia.org') return null;
  const page = COMMONS_FILE_PAGE.exec(pathname);
  return page && commonsTitle(page[1]);
}

function stringLiteralAfter(script: string, prefix: string): string | null {
  const start = script.indexOf(prefix);
  if (start < 0) return null;
  for (let i = start + prefix.length; i < script.length; i++) {
    const code = script.charCodeAt(i);
    if (code === 92) i++;
    else if (code === 34) return script.slice(start + prefix.length, i);
  }
  return null;
}

function scriptString(literal: string): string | null {
  const json = literal.replace(/\\(?:x([0-9a-fA-F]{2})|([\s\S]))/g, (escape, hex: string | undefined, char: string) =>
    hex ? `\\u00${hex}` : char === "'" ? "'" : escape,
  );
  try {
    return JSON.parse(`"${json}"`) as string;
  } catch {
    return null;
  }
}

export function deviantArtLabels(script: string): Map<string, boolean> {
  const labels = new Map<string, boolean>();
  const literal = stringLiteralAfter(script, DEVIANTART_STATE);
  const text = literal && scriptString(literal);
  if (!text) return labels;
  let state: unknown;
  try {
    state = JSON.parse(text);
  } catch {
    return labels;
  }
  const deviations = recordOf(recordOf(recordOf(state)['@@entities']).deviation);
  for (const deviation of Object.values(deviations).map(recordOf)) {
    const { baseUri } = recordOf(deviation.media);
    const key = typeof baseUri === 'string' ? labelKeyOf('deviantart', baseUri) : null;
    if (key) labels.set(key, deviation.isAiGenerated === true);
  }
  return labels;
}
